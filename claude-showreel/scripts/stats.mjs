// Counts the project's own code and writes src/stats.ts (shown on screen in the reveal and the credits).
// usage: node scripts/stats.mjs
import fs from 'fs';
import path from 'path';
const files = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, {withFileTypes: true})) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(tsx?|py|mjs)$/.test(e.name) && e.name !== 'stats.ts') files.push(p);
  }
};
['src', 'audio', 'scripts'].forEach(walk);
let lines = 0;
const sample = [];
for (const f of files.sort()) {
  const src = fs.readFileSync(f, 'utf8').split('\n');
  lines += src.filter((l) => l.trim()).length;
  if (/scenes|Root|make_audio/.test(f)) {
    sample.push(`// ${f}`);
    src.filter((l) => l.trim() && l.length < 90).slice(0, 14).forEach((l) => sample.push(l.slice(0, 64)));
    sample.push('');
  }
}
const out = `// generated by scripts/stats.mjs — do not edit
export const STATS = {lines: ${lines}, files: ${files.length}, frames: 9000, scenes: 17};
export const CODE_LINES: string[] = ${JSON.stringify(sample, null, 0)};
`;
fs.writeFileSync('src/stats.ts', out);
console.log('lines', lines, 'files', files.length, 'sample', sample.length);
